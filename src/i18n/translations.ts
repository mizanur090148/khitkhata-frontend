export type TranslationKey = keyof typeof translations.bn;

export function getTranslation(lang: Language, key: string, fallback?: string): string {
  if (lang === 'bn') {
    const val = (translations.bn as Record<string, string>)[key];
    if (val !== undefined) return val;
    return key;
  }

  // Check English dot-notation dictionary
  const enVal = (translations.en as Record<string, string>)[key];
  if (enVal !== undefined) return enVal;

  // Check direct Bengali-to-English phrase dictionary
  if (BENGALI_TO_ENGLISH[key]) {
    return BENGALI_TO_ENGLISH[key];
  }

  // Check trimmed phrase
  const trimmed = key.trim();
  if (BENGALI_TO_ENGLISH[trimmed]) {
    return BENGALI_TO_ENGLISH[trimmed];
  }

  return fallback || key;
}
